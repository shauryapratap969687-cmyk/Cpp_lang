#include <iostream>

int main() {
    double d1, d2; 

    std::cout << "Enter d1, d2 : ";
    std::cin >> d1 >> d2;

    std::cout << "Addition  = " << d1 + d2 << "\n";
    std::cout << "Subtraction  = " << d1 - d2 << "\n";
    std::cout << "Multiplication  = " << d1 * d2 << "\n";
    std::cout << "Division  = " << d1 / d2 << "\n";

    return 0;
} 